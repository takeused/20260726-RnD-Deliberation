"""심의기준 개정 시 이 파일만 수정하면 전체 에이전트에 반영된다."""

REVIEW_CRITERIA = """
## 국가 R&D 예산 심의 핵심 평가 기준

심의의 최우선 평가 항목은 다음 세 가지입니다. 모든 분석·질의·판단에서 이 기준을 우선 적용하세요.

1. **정부지원 필요성** (최우선)
   - 민간이 자체 수행할 수 없는 이유가 명확한가 (시장실패, 고위험·장기 투자, 공공재적 성격)
   - 정부 개입의 정당성: 왜 민간 투자나 금융 지원이 아닌 국가 R&D 예산이어야 하는가
   - 기존 정부 사업의 확대·개편으로 대응할 수 없고 신규 사업이어야 하는 근거가 있는가

2. **기술개발의 중요성**
   - 국가전략기술·상위 정책과의 부합성, 기술 주권·공급망·경제안보 관점의 전략적 가치
   - 성공 시 산업·경제·사회적 파급효과가 구체적 근거와 함께 제시되는가

3. **시급성**
   - 왜 지금 착수해야 하는가: 글로벌 경쟁 동향, 기술 격차 확대 위험, 투자 골든타임 논거
   - 착수를 1~2년 지연할 경우 발생할 비용·기회 상실이 구체적으로 제시되는가

보조 기준: 목표·성과지표의 구체성과 검증 가능성, 유사·중복 사업 여부, 수행체계와 예산 규모의 적정성.
"""


def get_review_criteria() -> str:
    """프롬프트 주입용 심의기준 텍스트 반환."""
