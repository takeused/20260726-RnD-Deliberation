# 국가 R&D 예산 심의 핵심 평가 기준 — 전 에이전트 프롬프트에 공통 주입되는 단일 정의
"""심의기준 개정 시 이 파일만 수정하면 전체 에이전트에 반영된다.

구조: 공통 핵심 기준(3대 기준) + 사업 유형 모듈(산업형·공공임무형·혼합형).
유형은 심의 시작 전에 코드가 한 번 판별해 상태(project_type)에 넣는다 (dataflows/project_type.py).
노드마다 LLM이 성격을 따로 판별하면 분석가와 재정 검토관이 서로 다른 잣대를 쓸 수 있어서다.
"""

from rdagents.dataflows.project_type import INDUSTRY, MIXED, PUBLIC

COMMON_CRITERIA = """
## 국가 R&D 예산 심의 핵심 평가 기준

심의의 최우선 평가 항목은 다음 세 가지입니다. 모든 분석·질의·판단에서 이 기준을 우선 적용하세요.

1. **정부지원 필요성** (최우선): 민간이 자체 수행할 수 없는 이유, 국가 R&D 예산이어야 하는 이유,
   기존 정부 사업의 확대·개편으로 대응할 수 없고 신규 사업이어야 하는 근거
2. **기술개발의 중요성**: 사업 성격에 맞는 국가적·사회적 가치와 상위 정책 부합성
3. **시급성**: 왜 지금 착수해야 하는가, 1~2년 지연할 때 무엇을 잃는가

보조 기준: 목표·성과지표의 구체성과 검증 가능성, 유사·중복 사업 여부, 수행체계와 예산 규모의 적정성.
"""

TYPE_MODULES = {
    PUBLIC: """
### 사업 유형: 공공임무형 (재난안전 등 사회문제 해결) — 이 기준으로 평가하세요
민간투자·수출·산업파급을 일률적으로 요구하지 말고 공익성, 정부 책무, 피해 저감과 사회 회복력을 우선 평가하세요.
- 정부지원 필요성: 국민의 생명·신체·재산 보호라는 국가·지방정부의 책무, 시장실패, 지역 간 안전격차
- 기술개발의 중요성 = 공공가치·피해저감 효과: 인명·재산 피해 저감, 예방·탐지·대응 시간 단축,
  취약계층·지역 안전격차 완화, 공공서비스 지속성과 사회 회복력을 측정 가능한 지표로 제시하는가
- 시급성: 재난의 반복·대형화, 기후·도시환경 변화, 노후 인프라, 현장 대응 공백. 지연 시 인명피해·피해비용
- 재난관리 단계 적합성: 예방·대비·대응·복구 중 어느 단계의 어떤 공백을 메우는가, 현장 요구와 맞는가
- 현장 적용·확산 경로: 수요기관(지자체·소방·재난관리 책임기관 등)이 기획부터 참여하는가, 실증 계획,
  제도화 경로(매뉴얼·표준·인증·법령·지침 반영, 조달 연계), 사업 종료 후 운영·유지관리 주체와 재원
- 수행체계: 부처 간 역할 분담과 중복 (재난안전 R&D는 여러 부처에 나뉘어 있다)
- 경제성: 화폐화가 타당할 때만 피해회피액 등으로 산정하고, 근거가 부족한 억지 B/C를 만들지 말고
  비용효과성, 다기준평가, 서비스 수준·대응시간·피해저감 지표를 사용하세요.
""",
    INDUSTRY: """
### 사업 유형: 산업형 (산업·시장 창출) — 이 기준으로 평가하세요
- 정부지원 필요성: 고위험·장기 투자로 인한 시장실패, 민간 투자만으로 안 되는 이유, 민간 매칭 계획
- 기술개발의 중요성: 기술 주권·공급망·경제안보, 기술 격차, 산업·경제 파급효과
- 시급성: 글로벌 경쟁, 기술 격차, 투자 골든타임. 지연 시 시장·기회 상실
- 사업화·확산 경로: 수요기업 참여, 기술이전·사업화 계획, 사업 종료 후 민간 주도 전환
- 경제성: 시장 규모와 점유 목표의 근거, 편익 산정의 보수성 (B/C를 쓰면 가정과 출처를 명시)
""",
    MIXED: """
### 사업 유형: 혼합형 (공공임무와 산업 창출이 섞임) — 이 기준으로 평가하세요
주된 성격이 무엇인지 근거와 함께 밝히고, 그 성격의 편익과 성과지표를 우선 적용하세요.
- 공공임무 측면: 정부 책무, 인명·재산 피해 저감, 대응시간, 지역 안전격차, 현장 적용·제도화 경로
- 산업 측면: 기술 주권·공급망, 산업 파급, 사업화·민간 매칭
- 한쪽 잣대로 다른 쪽을 감점하지 마세요 (재난안전 성과에 시장성을 요구하거나 그 반대).
- 경제성: 근거가 부족한 억지 B/C 대신 비용효과성·다기준평가를 함께 쓰세요.
""",
}


def get_review_criteria(project_type: str | None = None) -> str:
    """프롬프트 주입용 심의기준 텍스트 반환. 유형을 모르면 혼합형 기준."""
    return COMMON_CRITERIA + TYPE_MODULES.get(project_type or MIXED, TYPE_MODULES[MIXED])
