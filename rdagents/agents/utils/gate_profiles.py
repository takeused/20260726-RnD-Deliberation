def get_gate_profile(gate: str) -> str:
    """관문 이름으로 프로파일 텍스트 반환. 알 수 없는 관문이면 오류."""
    profile = GATE_PROFILES.get(gate)
    if profile is None:
        raise ValueError(
            f"알 수 없는 심의 관문: {gate} (사용 가능: {', '.join(GATE_PROFILES)})"
        )
    return profile
